-- The contract hash intentionally covers the migration identity/version,
-- rather than the SQL file's own self-referential registration statement.
DO $$
DECLARE
  expected_checksum char(64) := encode(digest('0011_iam_core:v1', 'sha256'), 'hex');
  existing_checksum char(64);
  existing_key text;
BEGIN
  SELECT checksum
  INTO existing_checksum
  FROM platform.schema_migration
  WHERE migration_key = '0011_iam_core';

  IF existing_checksum IS NOT NULL THEN
    IF lower(existing_checksum) <> lower(expected_checksum) THEN
      RAISE EXCEPTION
        'Migration 0011_iam_core checksum mismatch: database %, expected %',
        existing_checksum, expected_checksum;
    END IF;
    RETURN;
  END IF;

  SELECT migration_key
  INTO existing_key
  FROM platform.schema_migration
  WHERE version = 11;

  IF existing_key IS NOT NULL AND existing_key <> '0011_iam_core' THEN
    RAISE EXCEPTION
      'Migration version 11 is already registered as %', existing_key;
  END IF;

  INSERT INTO platform.schema_migration (
    migration_key, version, checksum, notes
  )
  VALUES (
    '0011_iam_core', 11, expected_checksum,
    'Stage A+B IAM core: identities, organizations, memberships, RBAC, sessions and invitations.'
  );
END
$$;

