BEGIN;

-- Stage A+B identity and access-management foundation.
--
-- PostgreSQL TIMESTAMPTZ stores an absolute instant (UTC internally).  The
-- application must format it for the user's timezone; no local wall-clock
-- timestamps are stored in these tables.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS platform;
CREATE SCHEMA IF NOT EXISTS iam;

CREATE TABLE IF NOT EXISTS platform.schema_migration (
  migration_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  migration_key text NOT NULL UNIQUE,
  version integer NOT NULL UNIQUE CHECK (version > 0),
  checksum char(64) NOT NULL CHECK (checksum ~ '^[0-9a-fA-F]{64}$'),
  applied_at timestamptz NOT NULL DEFAULT now(),
  applied_by text NOT NULL DEFAULT current_user,
  notes text
);

COMMENT ON TABLE platform.schema_migration IS
  'Applied database migrations. checksum is a stable migration-contract hash; rerunning a migration with a different checksum fails.';
COMMENT ON COLUMN platform.schema_migration.applied_at IS
  'Absolute UTC instant. PostgreSQL TIMESTAMPTZ is used intentionally.';

DO $$
BEGIN
  CREATE TYPE iam.user_status AS ENUM ('ACTIVE', 'SUSPENDED', 'DELETED');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
  CREATE TYPE iam.membership_status AS ENUM ('INVITED', 'ACTIVE', 'SUSPENDED', 'REMOVED');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
  CREATE TYPE iam.role_scope AS ENUM ('SYSTEM', 'ORGANIZATION');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
  CREATE TYPE iam.invitation_status AS ENUM ('PENDING', 'ACCEPTED', 'REVOKED', 'EXPIRED');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END
$$;

CREATE TABLE IF NOT EXISTS iam.user_account (
  user_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  identity_provider text NOT NULL DEFAULT 'local',
  external_subject text,
  email text,
  display_name text,
  status iam.user_status NOT NULL DEFAULT 'ACTIVE',
  email_verified boolean NOT NULL DEFAULT false,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (btrim(identity_provider) <> ''),
  CHECK (external_subject IS NULL OR btrim(external_subject) <> ''),
  CHECK (email IS NULL OR (btrim(email) = email AND position('@' IN email) > 1)),
  CHECK (display_name IS NULL OR btrim(display_name) <> '')
);

COMMENT ON TABLE iam.user_account IS
  'Application identity. OIDC/provider subject is the durable external identity key; no provider access token is stored here.';
COMMENT ON COLUMN iam.user_account.external_subject IS
  'Stable subject identifier from the configured identity provider, not an access token.';
COMMENT ON COLUMN iam.user_account.updated_at IS
  'Absolute UTC instant.';

CREATE TABLE IF NOT EXISTS iam.organization (
  organization_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_key text NOT NULL UNIQUE,
  organization_name text NOT NULL,
  legal_name text,
  status iam.user_status NOT NULL DEFAULT 'ACTIVE',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (organization_key ~ '^[a-zA-Z0-9][a-zA-Z0-9_-]{1,99}$'),
  CHECK (btrim(organization_name) <> ''),
  CHECK (legal_name IS NULL OR btrim(legal_name) <> '')
);

COMMENT ON TABLE iam.organization IS
  'Tenant boundary for enterprise projects, BOMs, calculations, conversations and uploads.';

CREATE TABLE IF NOT EXISTS iam.organization_membership (
  membership_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL
    REFERENCES iam.organization(organization_id) ON DELETE CASCADE,
  user_id uuid NOT NULL
    REFERENCES iam.user_account(user_id) ON DELETE CASCADE,
  membership_status iam.membership_status NOT NULL DEFAULT 'ACTIVE',
  joined_at timestamptz,
  invited_by uuid REFERENCES iam.user_account(user_id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (organization_id, user_id),
  CHECK (joined_at IS NULL OR joined_at >= created_at)
);

COMMENT ON TABLE iam.organization_membership IS
  'A user-to-organization membership. All tenant-scoped authorization resolves through this row.';

CREATE TABLE IF NOT EXISTS iam.role (
  role_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  role_key text NOT NULL UNIQUE,
  role_name_cn text NOT NULL,
  role_name_en text NOT NULL,
  role_scope iam.role_scope NOT NULL DEFAULT 'ORGANIZATION',
  description text,
  is_system_role boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (role_key ~ '^[a-z][a-z0-9_.-]{1,99}$'),
  CHECK (btrim(role_name_cn) <> ''),
  CHECK (btrim(role_name_en) <> '')
);

CREATE TABLE IF NOT EXISTS iam.permission (
  permission_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  permission_key text NOT NULL UNIQUE,
  resource_key text NOT NULL,
  action_key text NOT NULL,
  permission_name_cn text NOT NULL,
  permission_name_en text NOT NULL,
  description text,
  is_system_permission boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (permission_key ~ '^[a-z][a-z0-9_.-]{1,99}$'),
  CHECK (resource_key ~ '^[a-z][a-z0-9_.-]{0,49}$'),
  CHECK (action_key ~ '^[a-z][a-z0-9_.-]{0,49}$'),
  CHECK (btrim(permission_name_cn) <> ''),
  CHECK (btrim(permission_name_en) <> '')
);

CREATE TABLE IF NOT EXISTS iam.role_permission (
  role_id uuid NOT NULL
    REFERENCES iam.role(role_id) ON DELETE CASCADE,
  permission_id uuid NOT NULL
    REFERENCES iam.permission(permission_id) ON DELETE CASCADE,
  granted_at timestamptz NOT NULL DEFAULT now(),
  granted_by uuid REFERENCES iam.user_account(user_id) ON DELETE SET NULL,
  PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS iam.membership_role (
  membership_id uuid NOT NULL
    REFERENCES iam.organization_membership(membership_id) ON DELETE CASCADE,
  role_id uuid NOT NULL
    REFERENCES iam.role(role_id) ON DELETE RESTRICT,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  assigned_by uuid REFERENCES iam.user_account(user_id) ON DELETE SET NULL,
  PRIMARY KEY (membership_id, role_id)
);

CREATE TABLE IF NOT EXISTS iam.session (
  session_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL
    REFERENCES iam.user_account(user_id) ON DELETE CASCADE,
  session_token_hash char(64) NOT NULL UNIQUE,
  auth_provider text NOT NULL DEFAULT 'local',
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  ip_address inet,
  user_agent text,
  CHECK (session_token_hash ~ '^[0-9a-fA-F]{64}$'),
  CHECK (btrim(auth_provider) <> ''),
  CHECK (expires_at > created_at),
  CHECK (last_seen_at >= created_at),
  CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

-- A session has one explicit active organization context.  Membership is
-- checked by the application on every request; this nullable pointer allows
-- a user with memberships in multiple organizations to switch context while
-- keeping the session itself tenant-aware.
ALTER TABLE iam.session
  ADD COLUMN IF NOT EXISTS current_organization_id uuid
    REFERENCES iam.organization(organization_id) ON DELETE SET NULL;

COMMENT ON TABLE iam.session IS
  'Server-side session registry. Store only a SHA-256 token hash; the raw cookie token never enters PostgreSQL.';
COMMENT ON COLUMN iam.session.expires_at IS
  'Absolute UTC expiration instant.';
COMMENT ON COLUMN iam.session.current_organization_id IS
  'Current organization context selected for this session; application must verify an active membership before use.';

CREATE TABLE IF NOT EXISTS iam.invitation (
  invitation_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL
    REFERENCES iam.organization(organization_id) ON DELETE CASCADE,
  email text NOT NULL,
  invitation_token_hash char(64) NOT NULL UNIQUE,
  invited_by uuid REFERENCES iam.user_account(user_id) ON DELETE SET NULL,
  role_id uuid REFERENCES iam.role(role_id) ON DELETE RESTRICT,
  invitation_status iam.invitation_status NOT NULL DEFAULT 'PENDING',
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  accepted_at timestamptz,
  accepted_by uuid REFERENCES iam.user_account(user_id) ON DELETE SET NULL,
  revoked_at timestamptz,
  CHECK (btrim(email) = email AND position('@' IN email) > 1),
  CHECK (invitation_token_hash ~ '^[0-9a-fA-F]{64}$'),
  CHECK (expires_at > created_at),
  CHECK (accepted_at IS NULL OR accepted_at >= created_at),
  CHECK (revoked_at IS NULL OR revoked_at >= created_at),
  CHECK (NOT (accepted_at IS NOT NULL AND revoked_at IS NOT NULL))
);

COMMENT ON TABLE iam.invitation IS
  'One-time organization invitation. Only a token hash is stored; invitation acceptance is auditable through timestamps and user references.';

CREATE INDEX IF NOT EXISTS idx_user_account_status
  ON iam.user_account(status, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_account_provider_subject
  ON iam.user_account(identity_provider, external_subject)
  WHERE external_subject IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_account_email_ci
  ON iam.user_account(lower(email))
  WHERE email IS NOT NULL AND status <> 'DELETED'::iam.user_status;

CREATE INDEX IF NOT EXISTS idx_membership_user_status
  ON iam.organization_membership(user_id, membership_status);
CREATE INDEX IF NOT EXISTS idx_membership_org_status
  ON iam.organization_membership(organization_id, membership_status);

CREATE INDEX IF NOT EXISTS idx_role_scope
  ON iam.role(role_scope, role_key);
CREATE INDEX IF NOT EXISTS idx_permission_resource
  ON iam.permission(resource_key, action_key);
CREATE INDEX IF NOT EXISTS idx_role_permission_permission
  ON iam.role_permission(permission_id, role_id);
CREATE INDEX IF NOT EXISTS idx_membership_role_role
  ON iam.membership_role(role_id, membership_id);

CREATE INDEX IF NOT EXISTS idx_session_user_active
  ON iam.session(user_id, expires_at)
  WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_session_current_organization
  ON iam.session(current_organization_id, user_id)
  WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_session_expiry
  ON iam.session(expires_at)
  WHERE revoked_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_invitation_org_email_pending
  ON iam.invitation(organization_id, lower(email))
  WHERE invitation_status = 'PENDING'::iam.invitation_status
    AND revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_invitation_expiry
  ON iam.invitation(expires_at, invitation_status);

CREATE OR REPLACE FUNCTION platform.touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS trg_touch_user_account_updated_at ON iam.user_account;
CREATE TRIGGER trg_touch_user_account_updated_at
BEFORE UPDATE ON iam.user_account
FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

DROP TRIGGER IF EXISTS trg_touch_organization_updated_at ON iam.organization;
CREATE TRIGGER trg_touch_organization_updated_at
BEFORE UPDATE ON iam.organization
FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

DROP TRIGGER IF EXISTS trg_touch_membership_updated_at ON iam.organization_membership;
CREATE TRIGGER trg_touch_membership_updated_at
BEFORE UPDATE ON iam.organization_membership
FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

DROP TRIGGER IF EXISTS trg_touch_role_updated_at ON iam.role;
CREATE TRIGGER trg_touch_role_updated_at
BEFORE UPDATE ON iam.role
FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

DROP TRIGGER IF EXISTS trg_touch_permission_updated_at ON iam.permission;
CREATE TRIGGER trg_touch_permission_updated_at
BEFORE UPDATE ON iam.permission
FOR EACH ROW EXECUTE FUNCTION platform.touch_updated_at();

